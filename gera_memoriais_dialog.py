from . import leitura, calculos, geocuritiba, saida

# This loads your .ui file so that PyQt can populate your plugin with the elements from Qt Designer
FORM_CLASS, _ = uic.loadUiType(
    os.path.join(
        os.path.dirname(__file__),
        'gera_memoriais_dialog_base.ui'),
    from_imports=True,
    import_from='gera_memoriais')


class GeraMemoriaisDialog(QtWidgets.QDialog, FORM_CLASS):
    def __init__(self, parent=None):
        """Constructor."""
        super(GeraMemoriaisDialog, self).__init__(parent)
        # Set up the user interface from Designer through FORM_CLASS.
        # After self.setupUi() you can access any designer object by doing
        # self.<objectname>, and you can use autoconnect slots - see
        # http://qt-project.org/doc/qt-4.8/designer-using-a-ui-file.html
        # #widgets-and-dialogs-with-auto-connect
        self.setupUi(self)

        # planta: só arquivos DXF; quando um arquivo é escolhido, roda carregar_dxf
        self.seletor_dxf.setFilter("DXF (*.dxf)")
        self.seletor_dxf.fileChanged.connect(self.carregar_dxf)

        # saídas: escolher um arquivo NOVO para salvar
        self.seletor_saida.setStorageMode(QgsFileWidget.SaveFile)
        self.seletor_saida.setFilter("GeoPackage (*.gpkg)")
        self.seletor_docx.setStorageMode(QgsFileWidget.SaveFile)
        self.seletor_docx.setFilter("Word (*.docx)")

        # CAU: letra A, de 4 a 6 números, hífen e 1 número (ex.: A1234-5, A12345-6, A123456-7)
        regra_cau = QRegularExpression("[Aa][0-9]{4,6}-[0-9]")
        self.campo_cau.setValidator(QRegularExpressionValidator(regra_cau))

        # botão Gerar: roda gerar
        self.botao_gerar.clicked.connect(self.gerar)

    def carregar_dxf(self, caminho):
        """Preenche as listas com as camadas do CAD do DXF e marca a camada padrão."""
        if not caminho:
            return
        try:
            nomes = leitura.nomes_das_camadas(caminho)
        except ValueError:
            self.aviso("Não foi possível abrir a planta:\n" + caminho)
            return

        self.combo_quadras.clear()
        self.combo_quadras.addItems(nomes)
        self.combo_quadras.setCheckedItems(["QUADRAS_POL"])

        self.combo_quadras_rotulos.clear()
        self.combo_quadras_rotulos.addItems(nomes)
        self.combo_quadras_rotulos.setCheckedItems(["TXTNUMQUADRA"])

        self.combo_lotes.clear()
        self.combo_lotes.addItems(nomes)
        self.combo_lotes.setCheckedItems(["LOTES_POL"])

        self.combo_lotes_rotulos.clear()
        self.combo_lotes_rotulos.addItems(nomes)
        self.combo_lotes_rotulos.setCheckedItems(["TXTNLOTE"])

        self.combo_confrontantes.clear()
        self.combo_confrontantes.addItems(nomes)
        self.combo_confrontantes.setCheckedItems(["CONFRONTANTES_POL"])

        self.combo_confrontantes_rotulos.clear()
        self.combo_confrontantes_rotulos.addItems(nomes)
        self.combo_confrontantes_rotulos.setCheckedItems(["CONFRONTANTE"])

        self.combo_ruas.clear()
        self.combo_ruas.addItems(nomes)
        self.combo_ruas.setCheckedItems(["RUAS_POL"])

        self.combo_ruas_rotulos.clear()
        self.combo_ruas_rotulos.addItems(nomes)
        self.combo_ruas_rotulos.setCheckedItems(["TXTRUAS"])

    def aviso(self, texto):
        """Mostra uma caixa de aviso."""
        QtWidgets.QMessageBox.warning(self, "Gera Memoriais", texto)

    def gerar(self):
        """O roteiro: confere a janela, roda as etapas e salva o GeoPackage e o DOCX."""

        # ---------- conferir o que foi preenchido ----------
        caminho = self.seletor_dxf.filePath()
        crs = self.seletor_crs.crs()
        caminho_gpkg = self.seletor_saida.filePath()
        caminho_docx = self.seletor_docx.filePath()
        if not caminho:
            self.aviso("Escolha a planta (DXF).")
            return
        if not crs.isValid():
            self.aviso("Escolha o sistema de coordenadas (CRS) da planta.")
            return
        if not caminho_gpkg:
            self.aviso("Escolha onde salvar o GeoPackage.")
            return
        if not caminho_gpkg.lower().endswith(".gpkg"):
            caminho_gpkg = caminho_gpkg + ".gpkg"
        if not caminho_docx:                             # sem DOCX escolhido: usa o nome do GeoPackage
            caminho_docx = caminho_gpkg[:-5] + "_memoriais.docx"
        if not caminho_docx.lower().endswith(".docx"):
            caminho_docx = caminho_docx + ".docx"

        camadas = {
            "quadras": self.combo_quadras.checkedItems(),
            "quadras_txt": self.combo_quadras_rotulos.checkedItems(),
            "lotes": self.combo_lotes.checkedItems(),
            "lotes_txt": self.combo_lotes_rotulos.checkedItems(),
            "confrontantes": self.combo_confrontantes.checkedItems(),
            "confrontantes_txt": self.combo_confrontantes_rotulos.checkedItems(),
            "ruas": self.combo_ruas.checkedItems(),
            "ruas_txt": self.combo_ruas_rotulos.checkedItems(),
        }
        for nome in ["quadras", "quadras_txt", "lotes", "lotes_txt", "ruas", "ruas_txt"]:
            if len(camadas[nome]) == 0:
                self.aviso("Marque pelo menos uma camada na lista: " + nome)
                return

        # dados digitados na janela, iguais em todos os lotes
        cau = self.campo_cau.text().strip().upper()      # "a12345-6" vira "A12345-6"
        if not self.campo_cau.hasAcceptableInput():      # CAU incompleto: fica em branco ([PREENCHER])
            cau = ""
        dados = {
            "planta": self.campo_planta.text().strip(),
            "bairro": self.campo_bairro.text().strip(),
            "carimbo": self.campo_carimbo.text().strip(),
            "arquiteto": self.campo_arquiteto.text().strip(),
            "titulo": self.campo_titulo.currentText(),   # Arquiteta ou Arquiteto
            "cau": cau,
        }
        usar_geocuritiba = self.check_geocuritiba.isChecked()

        mensagens = []      # cada etapa escreve aqui o que aconteceu (vai para o painel de log)
        try:
            if usar_geocuritiba and crs.authid() != "EPSG:31982":
                mensagens.append("ATENÇÃO: o GeoCuritiba usa SIRGAS 2000 / UTM 22S (EPSG:31982); "
                                 "a planta está em " + crs.authid() + ".")

            # ---------- ETAPA 1: ler o DXF ----------
            lotes, quadras, terrenos, ruas = leitura.ler_planta(caminho, crs, camadas, mensagens)

            # ---------- ETAPA 2: vértices, lados e quadra de cada lote ----------
            lotes = calculos.montar_lotes(lotes, quadras, mensagens)

            # ---------- ETAPA 3: GeoCuritiba (opcional) ----------
            for lote in lotes:
                lote["cadastro"] = {}                     # sem GeoCuritiba, o cadastro fica vazio
            if usar_geocuritiba:
                # eixos de rua em volta do loteamento (é a primeira consulta: se falhar,
                # o serviço está fora do ar e as outras consultas nem são feitas)
                caixa = QgsRectangle()
                for lote in lotes:
                    caixa.combineExtentWith(lote["geometria"].boundingBox())
                eixos = geocuritiba.buscar_eixos(caixa)
                if eixos is None:
                    mensagens.append("GeoCuritiba: não foi possível acessar o serviço (sem internet?).")
                else:
                    # nome oficial de cada rua: o do eixo que passa dentro do polígono da rua
                    for rua in ruas:
                        oficial = geocuritiba.nome_oficial(rua, eixos)
                        if oficial:
                            rua["nome"] = oficial
                    # cadastro de cada lote e indicação fiscal de cada terreno de fora
                    for lote in lotes:
                        lote["cadastro"] = geocuritiba.consultar_lote(lote["ponto_interno"])
                    for terreno in terrenos:
                        ponto = terreno["geometria"].pointOnSurface().asPoint()
                        cadastro = geocuritiba.consultar_lote(ponto)
                        terreno["nome"] = geocuritiba.formatar_if(cadastro.get("indicacao_fiscal"))
            # o que ficou sem nome aparece como [PREENCHER] no memorial
            for terreno in terrenos:
                terreno["nome"] = terreno["nome"] or calculos.FALTA
            for rua in ruas:
                rua["nome"] = rua["nome"] or None

            # ---------- ETAPA 4: confrontantes ----------
            calculos.achar_confrontantes(lotes, terrenos, ruas)

            # ---------- ETAPA 5: a frente ----------
            for lote in lotes:
                lote["lados"] = calculos.ordenar_pela_frente(lote["lados"])

            # ---------- ETAPA 6: a esquina ----------
            for lote in lotes:
                lote["esquina"] = calculos.calcular_esquina(lote, terrenos, ruas)

            # ---------- ETAPA 7: área, forma e cadastro ----------
            for lote in lotes:
                calculos.completar_dados(lote)

            # ---------- ETAPA 8: GeoPackage e DOCX ----------
            # se o GeoPackage de saída já está aberto no mapa (de uma geração anterior),
            # a camada é retirada do mapa para o arquivo poder ser substituído
            for camada in list(QgsProject.instance().mapLayers().values()):
                if camada.source().split("|")[0].replace("\\", "/").lower() == caminho_gpkg.replace("\\", "/").lower():
                    QgsProject.instance().removeMapLayer(camada.id())
            saida.salvar_gpkg(lotes, crs, dados, caminho_gpkg, mensagens)
            saida.salvar_docx(lotes, dados, caminho_docx, mensagens)

        except Exception as erro:
            QgsMessageLog.logMessage("\n".join(mensagens) + "\nERRO: " + str(erro), "Gera Memoriais", Qgis.Critical)
            QtWidgets.QMessageBox.critical(self, "Gera Memoriais", "Erro ao gerar:\n" + str(erro))
            return

        # ---------- resumo no painel de log e resultado no mapa ----------
        for lote in sorted(lotes, key=saida.ordem):
            mensagens.append(f"--- quadra {lote['quadra']}, lote {lote['codigo']} ---")
            for lado in lote["lados"]:
                mensagens.append(f"{lado['vertice']} {lado['comprimento']:.2f} m -> {saida.texto_confrontantes(lado)}")
        for mensagem in mensagens:
            QgsMessageLog.logMessage(mensagem, "Gera Memoriais", Qgis.Info)

        camada = QgsVectorLayer(caminho_gpkg + "|layername=lotes", "lotes_memorial", "ogr")
        if camada.isValid():
            QgsProject.instance().addMapLayer(camada)
        QtWidgets.QMessageBox.information(
            self, "Gera Memoriais",
            f"{len(lotes)} lotes processados.\nGeoPackage: {caminho_gpkg}\nDOCX: {caminho_docx}\n"
            "Detalhes no painel Mensagens de Log, aba 'Gera Memoriais'.")
